    ContextCapabilities(boolean forwardCompatible) throws LWJGLException {
        try {
            GLCapabilities capabilities = GL.getCapabilities();
            for (Field field : ContextCapabilities.class.getFields()) {
                int modifiers = field.getModifiers();
                if (field.getType() != boolean.class || Modifier.isStatic(modifiers) || Modifier.isFinal(modifiers)) {
                    continue;
                }
                try {
                    Field capability = GLCapabilities.class.getField(field.getName());
                    field.setBoolean(this, capability.getBoolean(capabilities));
                } catch (NoSuchFieldException ignored) {
                }
            }
        } catch (IllegalAccessException e) {
            throw new RuntimeException(e);
        }
    }
